defined( 'ABSPATH' ) || exit;

add_action( 'after_setup_theme', static function () {
	add_theme_support( 'wp-block-styles' );
	add_theme_support( 'responsive-embeds' );
	add_theme_support( 'editor-styles' );
	add_editor_style( 'style.css' );
} );

/**
 * Fonts: Cairo (Arabic UI) + Inter (Latin fallback), display=swap.
 *
 * Self-hosted (perf audit #5/#6: the Google Fonts stylesheet was
 * render-blocking — 949 ms wasted on the home page — and its swap caused a
 * 0.132 CLS shift on the hero h1). The woff2 files and assets/css/fonts.css are
 * generated by scripts/fetch-fonts.mjs; never edit fonts.css by hand.
 * No third-party font request is left, so WP no longer adds the third-party
 * dns-prefetch resource hint either.
 */
add_action( 'wp_enqueue_scripts', static function () {
	$version    = wp_get_theme()->get( 'Version' );
	$fonts_rel  = 'assets/css/fonts.css';
	$font_deps  = array();

	if ( file_exists( get_theme_file_path( $fonts_rel ) ) ) {
		wp_enqueue_style(
			'nilad-fonts',
			get_theme_file_uri( $fonts_rel ),
			array(),
			$version
		);
		// style.css still loads after the @font-face rules; if the fonts file
		// is missing the dependency is dropped rather than silently killing
		// style.css (WP skips a style whose dependency is unregistered).
		$font_deps = array( 'nilad-fonts' );
	}

	// Block themes do not load style.css automatically — enqueue it explicitly.
	wp_enqueue_style(
		'nilad-style',
		get_stylesheet_uri(),
		$font_deps,
		$version
	);
}, 20 );

/**
 * Preload the one critical face: Cairo arabic, which paints the hero h1 and
 * all Arabic body copy — with the font already in flight, `swap` no longer
 * reflows that heading. Priority 1 puts it ahead of the stylesheet links
 * (wp_print_styles runs at 8).
 *
 * The href MUST be byte-identical to the `url()` in assets/css/fonts.css or the
 * browser treats it as a different resource and downloads the face twice
 * (measured: 31 KB wasted per page view). So no cache-busting query here.
 */
add_action( 'wp_head', static function () {
	$rel = 'assets/fonts/cairo-arabic.woff2';

	if ( ! file_exists( get_theme_file_path( $rel ) ) ) {
		return;
	}

	printf(
		'<link rel="preload" href="%s" as="font" type="font/woff2" crossorigin>' . "\n",
		esc_url( get_theme_file_uri( $rel ) )
	);
}, 1 );

/**
 * Reveal-on-scroll motion (approved design A).
 * Inline-only script; respects prefers-reduced-motion; content still visible without JS.
 */
add_action( 'wp_enqueue_scripts', static function () {
	wp_register_script( 'nilad-motion', false, array(), '0.1.0', true );
	wp_enqueue_script( 'nilad-motion' );
	wp_add_inline_script(
		'nilad-motion',
		'(function(){
			var els=document.querySelectorAll(".reveal");
			if(!els.length) return;
			if(!("IntersectionObserver" in window)||matchMedia("(prefers-reduced-motion: reduce)").matches){
				els.forEach(function(el){el.classList.add("in")});
				return;
			}
			var io=new IntersectionObserver(function(entries){
				entries.forEach(function(e){
					if(e.isIntersecting){e.target.classList.add("in");io.unobserve(e.target)}
				});
			},{threshold:.12,rootMargin:"0px 0px -6% 0px"});
			els.forEach(function(el){io.observe(el)});
		})();'
	);
}, 30 );
