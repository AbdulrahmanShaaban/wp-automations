#!/usr/bin/env node
/**
 * fetch-fonts.mjs — one-time: self-host Alexandria (Google Fonts, OFL licence)
 * inside the theme.
 *
 * Why: the P1 perf audit measured the Google Fonts stylesheet as render-blocking
 * on every page (5.6–14.4s wasted under the wp-env throttle). Shipping the
 * woff2 files from our own origin removes the third-party round trip — the
 * lesson applied at the birth of this project instead of patched later.
 *
 * Keeps ONLY the `arabic` and `latin` subsets (our content uses exactly those),
 * rewrites the src to a theme-relative path, and writes assets/css/fonts.css.
 * functions.php falls back to the CDN when that file is missing.
 *
 * Run: node scripts/fetch-fonts.mjs   (needs network; safe to re-run)
 */
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const THEME = path.join(ROOT, 'wp-content', 'themes', 'siraj-theme');
const FONT_DIR = path.join(THEME, 'assets', 'fonts');
const CSS_DIR = path.join(THEME, 'assets', 'css');
const CSS_OUT = path.join(CSS_DIR, 'fonts.css');

const WEIGHTS = [400, 500, 600, 700, 800];
const SUBSETS = new Set(['arabic', 'latin']);
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36';

const cssUrl = `https://fonts.googleapis.com/css2?family=Alexandria:wght@${WEIGHTS.join(';')}&display=swap`;
console.log(`==> GET ${cssUrl}`);
const cssRes = await fetch(cssUrl, { headers: { 'User-Agent': UA } });
if (!cssRes.ok) {
  console.error(`css fetch failed: ${cssRes.status} — functions.php will fall back to the CDN.`);
  process.exit(1);
}
const css = await cssRes.text();

// Google's CSS format: `/* subset */` comment immediately before each @font-face.
const blocks = [...css.matchAll(/\/\*\s*([a-z0-9-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)];
if (!blocks.length) {
  console.error('no @font-face blocks parsed — Google changed the format; review the parser.');
  process.exit(1);
}

await mkdir(FONT_DIR, { recursive: true });
await mkdir(CSS_DIR, { recursive: true });

let out =
  '/* Self-hosted Alexandria (Alexandria, SIL Open Font License 1.1).\n' +
  '   Generated by scripts/fetch-fonts.mjs — do not edit by hand. */\n';
let count = 0;
// Alexandria ships as a VARIABLE font: Google returns the same woff2 for every
// weight (verified by hash), so download each unique URL once and share it.
const byUrl = new Map();

for (const [, subset, block] of blocks) {
  if (!SUBSETS.has(subset)) continue;
  const w = block.match(/font-weight:\s*(\d+)/);
  const u = block.match(/url\((https:[^)]+\.woff2)\)/);
  if (!w || !u) continue;

  let file = byUrl.get(u[1]);
  if (!file) {
    file = `alexandria-${subset}.woff2`;
    const res = await fetch(u[1], { headers: { 'User-Agent': UA } });
    if (!res.ok) {
      console.error(`download failed ${u[1]} -> ${res.status}`);
      process.exit(1);
    }
    const buf = Buffer.from(await res.arrayBuffer());
    await writeFile(path.join(FONT_DIR, file), buf);
    console.log(`  ${file}  ${buf.length} bytes`);
    byUrl.set(u[1], file);
  }
  out += block.replace(u[1], `../fonts/${file}`) + '\n';
  count += 1;
}

const expected = WEIGHTS.length * SUBSETS.size;
if (count !== expected) {
  console.error(`expected ${expected} faces, got ${count} — check the parse.`);
  process.exit(1);
}

await writeFile(CSS_OUT, out, 'utf8');
console.log(`==> fonts.css written (${count} faces)`);
